"""Host-authenticated facade for the data-only Agent Forum.

The facade binds every write actor to a trusted host invocation. Never expose
bind_invocation or raw SQLiteAgentForum methods as model tools. A host must
create an invocation using its own operation ID, then expose only
invocation-bound operations to the selected agent turn.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Callable

from .agent_forum import (
    AgentProfile,
    ForumNotFoundError,
    Proposal,
    SQLiteAgentForum,
    SkillEntry,
    Vote,
    WorkEntry,
)
from .tools import (
    ExecutionContext,
    HostAuthorityError,
    HostAuthorityResolver,
    PermissionDeniedError,
)


FORUM_READ_SHARED = "forum:read:shared"
FORUM_READ_SELF = "forum:read:self"
FORUM_REGISTER = "forum:admin:register"
FORUM_PROPOSE = "forum:proposals:write"
FORUM_VOTE = "forum:proposals:vote"
FORUM_SUPERSEDE = "forum:proposals:supersede"
FORUM_MODERATE = "forum:moderate"
FORUM_CONSENSUS = "forum:system:consensus"
FORUM_WORK_WRITE = "forum:work:write"
FORUM_SKILL_WRITE = "forum:skills:write"


@dataclass(frozen=True, slots=True)
class AgentForumInvocation:
    """Opaque, host-issued identity for one agent turn.

    The issuer marker prevents accidentally reusing a token from another
    gateway instance. This is an in-process capability, not a credential and
    not a serializable authentication token.
    """

    principal_id: str
    agent_id: str
    operation_id: str
    permissions: frozenset[str]
    _issuer: object = field(repr=False, compare=False)


class AgentForumGateway:
    """Least-privilege facade over SQLiteAgentForum.

    MODEL_TOOL_METHODS is the explicit candidate allowlist for a host adapter;
    registration and consensus administration are deliberately excluded.

    agent_for_invocation is trusted host code. It receives the authenticated
    execution context, including its host-generated operation ID, and returns
    the one agent identity selected for that invocation. This supports a
    principal that owns multiple agent instances without accepting an
    agent_id from model/client arguments.
    """

    MODEL_TOOL_METHODS = (
        "propose",
        "list_proposals",
        "get_proposal",
        "vote",
        "votes_for",
        "record_work",
        "work_log",
        "record_skill",
        "skill_history",
        "supersede",
    )

    def __init__(
        self,
        forum: SQLiteAgentForum,
        authority: HostAuthorityResolver,
        agent_for_invocation: Callable[[ExecutionContext], str | None],
    ) -> None:
        if not isinstance(forum, SQLiteAgentForum):
            raise HostAuthorityError("a trusted SQLiteAgentForum is required")
        if not isinstance(authority, HostAuthorityResolver):
            raise HostAuthorityError("a trusted HostAuthorityResolver is required")
        if not callable(agent_for_invocation):
            raise HostAuthorityError("a trusted agent-binding resolver is required")
        self._forum = forum
        self._authority = authority
        self._agent_for_invocation = agent_for_invocation
        self._issuer = object()

    def bind_invocation(
        self, credential: Any, *, operation_id: str
    ) -> AgentForumInvocation:
        """Host-only: authenticate a request and bind its active agent.

        The operation ID must be generated by the embedding host, not supplied
        by a model or forwarded from an untrusted request body.
        """
        context = self._authority.resolve(credential, operation_id=operation_id)
        try:
            agent_id = self._agent_for_invocation(context)
        except Exception:
            raise HostAuthorityError("forum agent binding failed") from None
        if not isinstance(agent_id, str) or not agent_id.strip():
            raise HostAuthorityError("no active forum agent is bound to this invocation")
        try:
            self._forum.get_agent(agent_id)
        except ForumNotFoundError:
            raise HostAuthorityError("the bound forum agent is unknown or disabled") from None
        return AgentForumInvocation(
            context.principal_id,
            agent_id,
            context.operation_id or "",
            context.permissions,
            self._issuer,
        )

    def _check(self, invocation: AgentForumInvocation) -> AgentForumInvocation:
        if (
            not isinstance(invocation, AgentForumInvocation)
            or invocation._issuer is not self._issuer
            or not invocation.principal_id
            or not invocation.agent_id
            or not invocation.operation_id
            or not isinstance(invocation.permissions, frozenset)
        ):
            raise HostAuthorityError("a valid host-issued forum invocation is required")
        return invocation

    @staticmethod
    def _require(invocation: AgentForumInvocation, permission: str) -> None:
        if permission not in invocation.permissions:
            raise PermissionDeniedError("forum permission denied")

    @staticmethod
    def _shared(invocation: AgentForumInvocation) -> bool:
        return (
            FORUM_READ_SHARED in invocation.permissions
            or FORUM_MODERATE in invocation.permissions
        )

    def _require_read_scope(self, invocation: AgentForumInvocation) -> None:
        if not self._shared(invocation) and FORUM_READ_SELF not in invocation.permissions:
            raise PermissionDeniedError("forum read permission denied")

    def register_agent(
        self,
        invocation: AgentForumInvocation,
        agent_id: str,
        display_name: str,
        *,
        capabilities: tuple[str, ...] | list[str] = (),
    ) -> AgentProfile:
        """Host-admin operation. Never register this method as an agent tool."""
        actor = self._check(invocation)
        self._require(actor, FORUM_REGISTER)
        return self._forum.register_agent(
            agent_id, display_name, capabilities=capabilities
        )

    def list_agents(
        self, invocation: AgentForumInvocation
    ) -> tuple[AgentProfile, ...]:
        actor = self._check(invocation)
        if not self._shared(actor):
            raise PermissionDeniedError("shared agent-directory access is required")
        return self._forum.list_agents()

    def get_agent(
        self, invocation: AgentForumInvocation, agent_id: str
    ) -> AgentProfile:
        actor = self._check(invocation)
        if not self._shared(actor) and not (
            FORUM_READ_SELF in actor.permissions and agent_id == actor.agent_id
        ):
            raise ForumNotFoundError("agent does not exist")
        return self._forum.get_agent(agent_id)

    def propose(
        self,
        invocation: AgentForumInvocation,
        title: str,
        body: dict[str, Any],
        *,
        rationale: str = "",
        profound: bool = False,
    ) -> Proposal:
        actor = self._check(invocation)
        self._require(actor, FORUM_PROPOSE)
        return self._forum.propose(
            actor.agent_id, title, body, rationale=rationale, profound=profound
        )

    def list_proposals(
        self,
        invocation: AgentForumInvocation,
        state: str | None = None,
    ) -> tuple[Proposal, ...]:
        actor = self._check(invocation)
        self._require_read_scope(actor)
        proposals = self._forum.list_proposals(state)
        if self._shared(actor):
            return proposals
        return tuple(item for item in proposals if item.author_id == actor.agent_id)

    def get_proposal(
        self, invocation: AgentForumInvocation, proposal_id: str
    ) -> Proposal:
        actor = self._check(invocation)
        self._require_read_scope(actor)
        proposal = self._forum.get_proposal(proposal_id)
        if not self._shared(actor) and proposal.author_id != actor.agent_id:
            raise ForumNotFoundError("proposal does not exist")
        return proposal

    def vote(
        self,
        invocation: AgentForumInvocation,
        proposal_id: str,
        decision: str,
        *,
        rationale: str = "",
    ) -> tuple[Proposal, Vote]:
        actor = self._check(invocation)
        self._require(actor, FORUM_VOTE)
        return self._forum.vote(
            proposal_id, actor.agent_id, decision, rationale=rationale
        )

    def votes_for(
        self, invocation: AgentForumInvocation, proposal_id: str
    ) -> tuple[Vote, ...]:
        actor = self._check(invocation)
        self._require_read_scope(actor)
        votes = self._forum.votes_for(proposal_id)
        if self._shared(actor):
            return votes
        # Self scope exposes only this agent's own vote, whether or not it
        # authored the proposal. No other agent's vote or proposal metadata
        # is disclosed by this projection.
        return tuple(vote for vote in votes if vote.agent_id == actor.agent_id)

    def record_work(
        self,
        invocation: AgentForumInvocation,
        summary: str,
        *,
        detail: dict[str, Any] | None = None,
    ) -> WorkEntry:
        actor = self._check(invocation)
        self._require(actor, FORUM_WORK_WRITE)
        return self._forum.record_work(actor.agent_id, summary, detail=detail)

    def work_log(
        self,
        invocation: AgentForumInvocation,
        agent_id: str | None = None,
    ) -> tuple[WorkEntry, ...]:
        actor = self._check(invocation)
        self._require_read_scope(actor)
        target = actor.agent_id if agent_id is None else agent_id
        if not self._shared(actor) and target != actor.agent_id:
            raise ForumNotFoundError("agent work log does not exist")
        return self._forum.work_log(target)

    def record_skill(
        self,
        invocation: AgentForumInvocation,
        skill_name: str,
        *,
        confidence: float,
        note: str = "",
        evidence_reference: str = "",
    ) -> SkillEntry:
        actor = self._check(invocation)
        self._require(actor, FORUM_SKILL_WRITE)
        return self._forum.record_skill(
            actor.agent_id,
            skill_name,
            confidence=confidence,
            note=note,
            evidence_reference=evidence_reference,
        )

    def skill_history(
        self,
        invocation: AgentForumInvocation,
        skill_name: str,
        *,
        agent_id: str | None = None,
    ) -> tuple[SkillEntry, ...]:
        actor = self._check(invocation)
        self._require_read_scope(actor)
        target = actor.agent_id if agent_id is None else agent_id
        if not self._shared(actor) and target != actor.agent_id:
            raise ForumNotFoundError("agent skill history does not exist")
        return self._forum.skill_history(target, skill_name)

    def supersede(
        self,
        invocation: AgentForumInvocation,
        proposal_id: str,
        *,
        expected_version: int,
    ) -> Proposal:
        actor = self._check(invocation)
        if (
            FORUM_MODERATE not in actor.permissions
            and FORUM_SUPERSEDE not in actor.permissions
        ):
            raise PermissionDeniedError("proposal supersession permission denied")
        proposal = self._forum.get_proposal(proposal_id)
        if (
            FORUM_MODERATE not in actor.permissions
            and proposal.author_id != actor.agent_id
        ):
            raise PermissionDeniedError("only the proposal author or a moderator may supersede it")
        return self._forum.supersede(
            proposal_id, expected_version=expected_version
        )

    def resolve_consensus(
        self, invocation: AgentForumInvocation, proposal_id: str
    ) -> Proposal:
        """System-only maintenance operation; never expose as a model tool."""
        actor = self._check(invocation)
        self._require(actor, FORUM_CONSENSUS)
        return self._forum.resolve_consensus(proposal_id)
